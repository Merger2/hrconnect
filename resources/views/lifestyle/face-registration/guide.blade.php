To enroll your face, you need to:

1. **Locate the Face ID enrollment section**
   - Click on "Face ID Enroll" (profile icon) in the bottom navigation bar.

2. **Position for capture**
   - Ensure you're in a well‑lit area with your face clearly visible.
   - Hold the camera at eye level (screens height).
   - Keep your face fully visible inside the circular guide.

3. **Follow the liveness steps**
   - The system will prompt you to look straight ahead.
   - Then it will ask you to slowly turn your head left and right.
   - Finally, it will ask you to look straight ahead again.

4. **Capture your face**
   - Once all steps are completed successfully, the "Capture Face" button will become active.
   - Press it to record your facial descriptor in our secure database.

5. **Verification**
   - After enrollment, you can test your Face ID by using it to clock‑in/out through the dashboard or attendance pages.
   - If the system identifies you correctly, the system will mark you as "present”.

**Important notes:**
- You must have your face visible in the camera’s field of view at all times.
- Avoid shadows, reflective surfaces, or extreme lighting.
- The process takes about 30‑60 seconds per enrollment.

If you encounter any issues, please contact support or refresh the page.